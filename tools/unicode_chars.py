#!/usr/bin/env python3
"""Scan the thesis .tex sources for non-ASCII characters and write unicode-chars.tex,
which maps each one to a pdfLaTeX-safe command (keeps Type 1 fonts, as the Graduate
School requires).  Unknown characters are reported so a mapping can be added here."""
import os, re, sys, unicodedata
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GREEK = {'α':'alpha','β':'beta','γ':'gamma','δ':'delta','ε':'epsilon','ζ':'zeta','η':'eta','θ':'theta','κ':'kappa','λ':'lambda',
         'ν':'nu','ξ':'xi','π':'pi','ρ':'rho','σ':'sigma','τ':'tau','φ':'phi','χ':'chi','ψ':'psi','ω':'omega','ϕ':'phi','ϵ':'epsilon',
         'Γ':'Gamma','Δ':'Delta','Θ':'Theta','Λ':'Lambda','Ξ':'Xi','Π':'Pi','Σ':'Sigma','Φ':'Phi','Ψ':'Psi','Ω':'Omega'}
MAP = {
 'µ': r'\textmu{}', 'μ': r'\textmu{}', '±': r'\ensuremath{\pm}', '×': r'\ensuremath{\times}', '·': r'\ensuremath{\cdot}', '•': r'\ensuremath{\cdot}',
 '≈': r'\ensuremath{\approx}', '≤': r'\ensuremath{\leq}', '≥': r'\ensuremath{\geq}', '≠': r'\ensuremath{\neq}', '∼': r'\ensuremath{\sim}',
 '∝': r'\ensuremath{\propto}', '∞': r'\ensuremath{\infty}', '→': r'\ensuremath{\rightarrow}', '←': r'\ensuremath{\leftarrow}',
 '↔': r'\ensuremath{\leftrightarrow}', '⟨': r'\ensuremath{\langle}', '⟩': r'\ensuremath{\rangle}', '√': r'\ensuremath{\surd}',
 '∑': r'\ensuremath{\sum}', '∫': r'\ensuremath{\int}', '∆': r'\ensuremath{\Delta}', '∂': r'\ensuremath{\partial}', '∈': r'\ensuremath{\in}',
 '−': r'\textminus{}', '‒': '--', '–': '--', '—': '---', '‐': '-', '‑': '-', ' ': r'\,', ' ': r'\,', '​': '',
 ' ': ' ', ' ': r'\quad{}', ' ': ' ', ' ': r'\,', ' ': r'\,', ' ': r'\,',
 '°': r'\textdegree{}', '℃': r'\textdegree{}C', 'Å': r'\AA{}', '‰': r'\textperthousand{}', '©': r'\textcopyright{}', '®': r'\textregistered{}',
 '™': r'\texttrademark{}', '…': r'\ldots{}', '′': r'\ensuremath{^{\prime}}', '″': r'\ensuremath{^{\prime\prime}}', '‘': '`', '’': "'", '“': '``', '”': "''",
 '¹': r'\textsuperscript{1}', '²': r'\textsuperscript{2}', '³': r'\textsuperscript{3}', '⁰': r'\textsuperscript{0}', '⁴': r'\textsuperscript{4}',
 '⁵': r'\textsuperscript{5}', '⁶': r'\textsuperscript{6}', '⁷': r'\textsuperscript{7}', '⁸': r'\textsuperscript{8}', '⁹': r'\textsuperscript{9}',
 '⁻': r'\textsuperscript{\textminus}', '⁺': r'\textsuperscript{+}', '₀': r'\textsubscript{0}', '₁': r'\textsubscript{1}', '₂': r'\textsubscript{2}',
 '₃': r'\textsubscript{3}', '₄': r'\textsubscript{4}', 'ᵢ': r'\textsubscript{i}', 'ₓ': r'\textsubscript{x}', 'Ɵ': r'\ensuremath{\theta}',
 'ˆ': r'\^{}', '̂': r'\^{}', 'ϴ': r'\ensuremath{\Theta}', '⊥': r'\ensuremath{\perp}', '∥': r'\ensuremath{\parallel}', '∗': r'\ensuremath{\ast}',
 '∣': r'\ensuremath{\mid}', '≡': r'\ensuremath{\equiv}', '∓': r'\ensuremath{\mp}', 'ℓ': r'\ensuremath{\ell}', '⋅': r'\ensuremath{\cdot}',
 '∙': r'\ensuremath{\cdot}', '∕': '/', '⁄': '/', '■': r'\ensuremath{\blacksquare}', '□': r'\ensuremath{\square}', '✓': r'\ensuremath{\checkmark}',
 'ø': r'\o{}', 'Ø': r'\O{}', 'ß': r'\ss{}', 'æ': r'\ae{}', 'œ': r'\oe{}', 'ı': r'\i{}', 'ł': r'\l{}', 'Ł': r'\L{}', 'đ': r'\dj{}',
 '﻿': '', '­': r'\-', '‧': r'\ensuremath{\cdot}', '∘': r'\ensuremath{\circ}', 'ʹ': "'", 'ǀ': '|', '∶': ':',
}
for g, n in GREEK.items(): MAP[g] = r'\ensuremath{\%s}' % n
# T1-encodable Latin-1 / Latin Extended-A letters are handled by inputenc natively.
def native(ch):
    try:
        ch.encode('latin-1')
        return unicodedata.category(ch).startswith('L')
    except UnicodeEncodeError:
        return unicodedata.category(ch).startswith('L') and unicodedata.name(ch, '').startswith('LATIN')
def math_alnum(ch):
    n = unicodedata.name(ch, '')
    return n.startswith('MATHEMATICAL ')
def main():
    chars = {}
    for d, dirs, fs in os.walk(ROOT):
        dirs[:] = [x for x in dirs if x not in ('tools', '.git')]
        for f in fs:
            if (f.endswith('.tex') or f.endswith('.bib')) and f != 'unicode-chars.tex':
                for ch in open(os.path.join(d, f), encoding='utf8').read():
                    if ord(ch) > 127: chars[ch] = chars.get(ch, 0) + 1
    lines, unknown = ['% Generated by tools/unicode_chars.py -- maps Unicode characters to pdfLaTeX commands.'], []
    for ch in sorted(chars):
        if ch in MAP: rep = MAP[ch]
        elif math_alnum(ch):
            base = unicodedata.normalize('NFKC', ch)
            name = unicodedata.name(ch)
            rep = (r'\ensuremath{\boldsymbol{%s}}' if 'BOLD' in name else r'\ensuremath{%s}') % (('\\' + GREEK[base]) if base in GREEK else base)
        elif native(ch): continue
        else:
            unknown.append('%s U+%04X %s (%d)' % (ch, ord(ch), unicodedata.name(ch, '?'), chars[ch])); continue
        lines.append(r'\newunicodechar{%s}{%s}' % (ch, rep))
    open(os.path.join(ROOT, 'unicode-chars.tex'), 'w', encoding='utf8').write('\n'.join(lines) + '\n')
    print(len(lines) - 1, 'mappings written;', 'unknown:' if unknown else 'no unknown characters', *unknown, sep='\n  ')
main()
